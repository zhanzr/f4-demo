uint8_t OV7670_ApplyConfig(void)
{
    /* soft reset */
    if (SCCB_BB_WriteReg(0x12, 0x80)) return 1;
    {
        volatile uint32_t w;
        for (w = 0; w < 2000000; w++) { }   /* ~50 ms */
    }
    for (uint32_t i = 0; i < (sizeof(reg_tbl) / sizeof(reg_tbl[0])); i++)
    {
        if (SCCB_BB_WriteReg(reg_tbl[i][0], reg_tbl[i][1])) return 2;
    }
    return 0;
}

void OV7670_OpenMvRgbTweak(void)
{
    /* COM15 = 0xD0: RGB565 + output range 00..FF (full).
     * (ALIENTEK table ended with 0x10 = RGB565 + 10..F0 limited range -
     *  that's the dark/washed "color curve", and 0x8217 = 0x82 0x17 is not
     *  a valid RGB565 bar.) */
    SCCB_BB_WriteReg(0x40, 0xD0);

    /* OpenMV: rewrite CLKRC last for clean RGB565. */
    SCCB_BB_WriteReg(0x11, 0x00);
}

void OV7670_ColorBarOn(void)
{
    /* Only toggle bit7 of SCALING_YSC (color-bar enable); preserve the
     * VGA scaling factors (XSC=0x3A, YSC=0x35) - clobbering them with
     * QVGA values corrupts the row geometry (the diagonal bug). */
    uint8_t xsc = SCCB_BB_ReadReg(0x70);
    uint8_t ysc = SCCB_BB_ReadReg(0x71);
    SCCB_BB_WriteReg(0x70, (uint8_t)(xsc & 0x7FU));
    SCCB_BB_WriteReg(0x71, (uint8_t)((ysc & 0x7FU) | 0x80U));
}

void OV7670_ColorBarOff(void)
{
    uint8_t xsc = SCCB_BB_ReadReg(0x70);
    uint8_t ysc = SCCB_BB_ReadReg(0x71);
    SCCB_BB_WriteReg(0x70, (uint8_t)(xsc & 0x7FU));
    SCCB_BB_WriteReg(0x71, (uint8_t)(ysc & 0x7FU));
}